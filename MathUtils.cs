namespace CSharpLab
{
	public class Helper
	{
		/// <summary>
		/// Метод для сложения двух чисел.
		/// </summary>
		/// <param name="a">Первое число.</param>
		/// <param name="b">Второе число.</param>
		/// <returns>Сумма чисел a и b.</returns>
		public static int AddNumbers(int a, int b)
		{
			return a + b;
		}
	}
}
